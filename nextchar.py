"""
Use the trained ByteGPT model to predict the next N characters/bytes.

Run with no arguments to be prompted interactively:
    python nextchar.py

Or use flags directly:
    python nextchar.py -p "The quick brown fox" -n 200
    python nextchar.py -p "Wikipedia" -n 100 -t 0.8
    python nextchar.py --file seed.txt -n 500 --temperature 1.2
"""

import argparse
import os

import torch

from model import ByteGPT, config


def load_model(model_path="lm.pth", device=None):
    """Load trained weights from lm.pth into a ByteGPT model (eval mode)."""
    if device is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"

    model = ByteGPT(
        vocab_size=config["vocab_size"],
        n_embd=config["n_embd"],
        n_layer=config["n_layer"],
        n_head=config["n_head"],
        block_size=config["block_size"],
        dropout=0.0,  # no dropout during inference
    ).to(device)

    if os.path.exists(model_path):
        model.load_state_dict(torch.load(model_path, map_location=device))
    else:
        print(f"  WARNING: {model_path} not found — using untrained weights. "
              f"Run `python model.py` to train first for meaningful predictions.")
    model.eval()
    return model, device


def predict(model, device, prompt_bytes, num_chars, temperature=1.0, top_k=0):
    """
    Autoregressively generate `num_chars` bytes after `prompt_bytes`.

    Returns:
        (prompt_bytes, generated_bytes) — the original prompt and the new bytes
    """
    idx = torch.tensor(list(prompt_bytes), dtype=torch.long, device=device).unsqueeze(0)

    with torch.no_grad():
        out = model.generate(idx, max_new_tokens=num_chars,
                             temperature=temperature, top_k=top_k)

    # out includes the prompt; strip it off to get only the generated bytes
    full = out[0].tolist()
    generated = bytes(full[len(prompt_bytes):])
    return bytes(prompt_bytes), generated


def main():
    parser = argparse.ArgumentParser(
        description="Predict the next characters using a trained ByteGPT model."
    )
    parser.add_argument(
        "-p", "--prompt", default=None,
        help="Text prompt to continue (if omitted, asks interactively)",
    )
    parser.add_argument(
        "-n", "--num", type=int, default=None,
        help="Number of characters to predict (if omitted, asks interactively)",
    )
    parser.add_argument(
        "--topk", type=int, default=10,
        help="Print top-K most likely bytes with probabilities each step (default: 10)",
    )
    parser.add_argument(
        "-t", "--temperature", type=float, default=1.0,
        help="Sampling temperature: lower = more deterministic (default: 1.0)",
    )
    parser.add_argument(
        "-m", "--model", default="lm.pth",
        help="Path to trained weights (default: lm.pth)",
    )
    parser.add_argument(
        "--file", default=None,
        help="Read the prompt from a text file instead of --prompt",
    )
    parser.add_argument(
        "--device", default=None,
        help="cuda or cpu (default: auto-detect)",
    )
    args = parser.parse_args()

    # --- Interactive input (when flags are missing) --------------------------
    if not args.file and args.prompt is None:
        args.prompt = input("Enter prompt text: ")

    if args.num is None:
        while True:
            value = input("Number of characters to predict: ").strip()
            try:
                args.num = int(value)
                if args.num <= 0:
                    print("  Please enter a positive number.")
                    continue
                break
            except ValueError:
                print("  Invalid number — please enter an integer.")

    # --- Get prompt bytes ----------------------------------------------------
    if args.file:
        with open(args.file, "rb") as f:
            prompt_bytes = f.read()
    else:
        prompt_bytes = args.prompt.encode("utf-8")

    if len(prompt_bytes) == 0:
        parser.error("prompt is empty — provide --prompt or --file")

    # --- Load model ----------------------------------------------------------
    print(f"Loading model from {args.model} ...")
    model, device = load_model(args.model, args.device)
    print(f"Device: {device} | Prompt: {len(prompt_bytes)} bytes | "
          f"Generating: {args.num} bytes | Temp: {args.temperature} | "
          f"Top-K: {args.topk if args.topk > 0 else 'off'}")
    print("-" * 60)

    # --- Predict -------------------------------------------------------------
    prompt, generated = predict(model, device, prompt_bytes, args.num,
                                args.temperature, args.topk)

    # --- Print result --------------------------------------------------------
    print(prompt.decode("utf-8", errors="replace"), end="")
    print(generated.decode("utf-8", errors="replace"), end="")
    print()
    print("-" * 60)
    print(f"Generated {len(generated)} bytes.")


if __name__ == "__main__":
    main()
